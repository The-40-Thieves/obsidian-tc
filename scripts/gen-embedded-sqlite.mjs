#!/usr/bin/env node
// THE-663 follow-up: bake a vanilla SQLite into the darwin standalone binaries, so sqlite-vec can
// be loaded at all on macOS.
//
// `bun:sqlite` uses APPLE'S SYSTEM SQLite on macOS, and Apple builds it without extension support:
//
//   RESULT=refused: This build of sqlite3 does not support dynamic extension loading
//
// measured directly on macos-14 and macos-26 runners. So db.loadExtension() cannot work there no
// matter how correctly vec0 is embedded — which is exactly what v1.14.0's publish run reported the
// first time THE-663's smoke gate ever executed (it lives in publish.yml, which only runs on a
// tag). The same embedded-vec0 mechanism reports vec=on on linux, so the embedding was never the
// problem; the LOADER was, and it is an Apple constraint rather than a bug of ours.
//
// Bun's documented escape hatch is Database.setCustomSQLite(path), pointing at a vanilla build,
// called before any Database is constructed. This script produces the library that call needs.
//
// UNIVERSAL2, not thin-per-target. GitHub no longer offers an x86_64 macOS runner, so publish.yml
// cross-compiles bun-darwin-x64 on an arm64 host and never executes it — only bun-darwin-arm64 is
// smoke:true. Both darwin targets therefore embed the SAME fat dylib: the arm64 slice is genuinely
// runtime-tested every release, dyld selects the right slice at load, and a future drift in the
// host->target mapping cannot ship arm64 code inside the x64 binary. Costs ~1.7 MB more than a thin
// slice against a ~100 MB binary.
//
// Like gen-embedded-vec.mjs this is a PER-BUILD artifact, not source: publish.yml regenerates it
// immediately before compiling each darwin target and never commits the result. The value in git is
// the empty placeholder, which every other path (`bun run`, the npm dist build, every test suite)
// keeps — outside a --compile darwin binary the adapter never reads it.
//
// Usage:
//   node scripts/gen-embedded-sqlite.mjs --target bun-darwin-arm64
//   node scripts/gen-embedded-sqlite.mjs --target bun-darwin-x64 --dylib /path/to/prebuilt.dylib
//   node scripts/gen-embedded-sqlite.mjs --reset          # restore the empty placeholder
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "packages/server/src/db/sqlite-embedded.ts");

// Pinned. NOTE THE HASH ALGORITHM: sqlite.org's download.html PRODUCT lines publish SHA3-256, not
// SHA-256 — pinning the published digest with a SHA-256 checker fails on a byte-perfect download.
// SHA3 below is the published value; SHA256 was computed from the artifact whose SHA3-256 matches
// it and whose size matches the published 3283177 bytes. Node has SHA3 via crypto, so both are
// verified here rather than picking whichever one the shell happens to support.
const SQLITE = {
  version: "3.53.4",
  url: "https://sqlite.org/2026/sqlite-autoconf-3530400.tar.gz",
  dir: "sqlite-autoconf-3530400",
  size: 3283177,
  sha3_256: "454e45f61c6bd75b7420e7190732dea03ce6639c63ada47bbc592f67fc340338",
  sha256: "0e9483900e92cd5de8fd48d16bf9200145a61f7fd5be542a5ac81d8a9516eb9c",
};

// Only darwin needs this. bun:sqlite bundles its own extension-capable SQLite on linux and windows,
// where the embedded vec0 already works — shipping a second SQLite there would be dead weight.
const DARWIN_TARGETS = new Set(["bun-darwin-x64", "bun-darwin-arm64"]);

const PLACEHOLDER_BANNER = `// GENERATED by scripts/gen-embedded-sqlite.mjs — DO NOT EDIT BY HAND.
//
// A vanilla, extension-capable SQLite for the darwin standalone binaries. bun:sqlite uses Apple's
// system SQLite on macOS, which is built WITHOUT extension support, so db.loadExtension() — and
// therefore all of dense retrieval — cannot work there without this. See db/bun-sqlite.ts for the
// setCustomSQLite() call that consumes it, and this script's header for the full rationale.
//
// PER-BUILD artifact, not source: publish.yml regenerates this for each darwin --compile target
// immediately before compiling, and never commits the result. The value in git is the empty
// placeholder below; every non-darwin target and every non-compiled path keeps it, and the adapter
// treats empty as "nothing to do".
//
// Regenerate with \`node scripts/gen-embedded-sqlite.mjs --target <bun-darwin-x64|bun-darwin-arm64>\`.
`;

const emit = (b64, note) =>
  writeFileSync(
    OUT,
    `${PLACEHOLDER_BANNER}
/** Base64-encoded universal2 libsqlite3.dylib (x86_64 + arm64), extension-capable.
 *  ${note} */
export const EMBEDDED_SQLITE_BASE64 = "${b64}";
`,
  );

const argv = process.argv.slice(2);
const flag = (name) => {
  const i = argv.indexOf(name);
  return i === -1 ? undefined : argv[i + 1];
};

if (argv.includes("--reset")) {
  emit("", "Empty in source control; only ever non-empty inside a compiled darwin release binary.");
  console.log(`gen-embedded-sqlite: reset ${OUT} to the empty placeholder`);
  process.exit(0);
}

const target = flag("--target");
if (!target || !DARWIN_TARGETS.has(target)) {
  console.error(
    `gen-embedded-sqlite: --target must be one of ${[...DARWIN_TARGETS].join(", ")} (got "${target ?? ""}").\n` +
      "Only darwin needs an embedded SQLite: bun:sqlite bundles an extension-capable build on linux and windows.",
  );
  process.exit(1);
}

// Resolve a symlink before measuring or stripping. libsqlite3.dylib is a link to
// libsqlite3.<version>.dylib, and stat() on the link reports 23 bytes — which silently turned an
// earlier run's strip measurements into nonsense.
function resolveDylib(dir) {
  const link = join(dir, "libsqlite3.dylib");
  if (!existsSync(link)) return undefined;
  let real;
  try {
    real = readlinkSync(link);
  } catch {
    real = "libsqlite3.dylib";
  }
  return join(dir, real);
}

function sh(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: "utf8", ...opts });
}

// Assert the ARTIFACT, never the exit code. sqlite's autosetup configure has been caught twice
// exiting 0 on failure: it silently accepts flags that do not exist (--enable-load-extension), and
// it printed "Could not find a C compiler" and still returned success, after which make ran.
function buildUniversal() {
  if (process.platform !== "darwin") {
    console.error(
      `gen-embedded-sqlite: --target ${target} needs a darwin host to build the dylib (this is ${process.platform}).\n` +
        "Pass --dylib <path> to embed a prebuilt universal2 library instead.",
    );
    process.exit(1);
  }
  const work = mkdtempSync(join(tmpdir(), "otc-sqlite-embed-"));
  const tgz = join(work, "sqlite.tar.gz");
  console.log(`gen-embedded-sqlite: fetching SQLite ${SQLITE.version}...`);
  sh("curl", ["-sSL", "--fail", "-o", tgz, SQLITE.url]);

  const bytes = readFileSync(tgz);
  if (bytes.length !== SQLITE.size) {
    console.error(`gen-embedded-sqlite: size ${bytes.length} != expected ${SQLITE.size}`);
    process.exit(1);
  }
  // Both digests, so neither a SHA3/SHA256 mix-up nor a single stale constant can pass silently.
  for (const [alg, want] of [
    ["sha256", SQLITE.sha256],
    ["sha3-256", SQLITE.sha3_256],
  ]) {
    const got = createHash(alg).update(bytes).digest("hex");
    if (got !== want) {
      console.error(`gen-embedded-sqlite: ${alg} ${got} != expected ${want}`);
      process.exit(1);
    }
  }
  console.log("gen-embedded-sqlite: sha256 + sha3-256 both verified");

  sh("tar", ["xzf", tgz, "-C", work]);
  const src = join(work, SQLITE.dir);

  const slices = [];
  for (const [arch, host] of [
    ["arm64", "aarch64-apple-darwin"],
    ["x86_64", "x86_64-apple-darwin"],
  ]) {
    const prefix = join(work, `out-${arch}`);
    try {
      sh("make", ["distclean"], { cwd: src, stdio: "ignore" });
    } catch {
      // first pass has no Makefile yet
    }
    // CC is set EXPLICITLY. With only --host, autosetup hunts for a prefixed compiler
    // (aarch64-apple-darwin-cc) that does not exist on macOS, where one clang is driven by -arch.
    // There is deliberately no --enable-load-extension: the flag does not exist, loading is on by
    // default, and this configure accepts unknown flags silently — so it would enforce nothing.
    sh("sh", ["-c", `./configure --prefix="${prefix}" --host="${host}" --disable-static`], {
      cwd: src,
      stdio: "ignore",
      env: { ...process.env, CC: "clang", CFLAGS: `-arch ${arch}`, LDFLAGS: `-arch ${arch}` },
    });
    sh("make", ["-j3"], { cwd: src, stdio: "ignore" });
    sh("make", ["install"], { cwd: src, stdio: "ignore" });

    const dylib = resolveDylib(join(prefix, "lib"));
    if (!dylib) {
      console.error(`gen-embedded-sqlite: no dylib produced for ${arch} — the build failed`);
      process.exit(1);
    }
    // A cross build that silently produced the HOST arch twice would lipo into a "universal" file
    // with two identical slices, pass every cheap check, and ship arm64 code inside the x64 binary
    // that nothing in CI ever executes. Checking each slice by name before fusing is the only
    // place that is catchable.
    const info = sh("lipo", ["-info", dylib]);
    if (!info.includes(arch)) {
      console.error(`gen-embedded-sqlite: ${dylib} is not ${arch} — ${info.trim()}`);
      process.exit(1);
    }
    // -S drops debug symbols, -x drops non-global ones; the sqlite3_* API bun:sqlite dlsym()s is
    // global and retained. Measured 5,181,936 -> 1,150,400 bytes on the linux equivalent.
    sh("strip", ["-S", "-x", dylib]);
    console.log(`gen-embedded-sqlite: ${arch} slice ${statSync(dylib).size} bytes`);
    slices.push(dylib);
  }

  const fat = join(work, "libsqlite3.dylib");
  sh("lipo", ["-create", ...slices, "-output", fat]);
  // AFTER lipo and strip, never before: modifying a Mach-O invalidates its signature, and arm64
  // refuses to dlopen an unsigned dylib with a symptom that looks exactly like the original bug.
  // The signature is embedded in the Mach-O, so it survives the base64 round trip at runtime.
  sh("codesign", ["-s", "-", "-f", fat]);
  sh("codesign", ["--verify", "--strict", fat]);

  const fatInfo = sh("lipo", ["-info", fat]);
  if (!(fatInfo.includes("x86_64") && fatInfo.includes("arm64"))) {
    // lipo -create succeeds silently with a single input, so "a file appeared" proves nothing.
    console.error(`gen-embedded-sqlite: fat dylib is missing a slice — ${fatInfo.trim()}`);
    process.exit(1);
  }
  console.log(`gen-embedded-sqlite: universal2 ${statSync(fat).size} bytes — ${fatInfo.trim()}`);

  const out = readFileSync(fat);
  rmSync(work, { recursive: true, force: true });
  return out;
}

const prebuilt = flag("--dylib");
let dylibBytes;
if (prebuilt) {
  if (!existsSync(prebuilt)) {
    console.error(`gen-embedded-sqlite: --dylib ${prebuilt} does not exist`);
    process.exit(1);
  }
  dylibBytes = readFileSync(prebuilt);
} else {
  dylibBytes = buildUniversal();
}

if (dylibBytes.length === 0) {
  console.error("gen-embedded-sqlite: dylib is empty — refusing to embed nothing");
  process.exit(1);
}

emit(
  dylibBytes.toString("base64"),
  `SQLite ${SQLITE.version}, ${dylibBytes.length} bytes, embedded for ${target}.`,
);
console.log(
  `gen-embedded-sqlite: wrote ${OUT} (SQLite ${SQLITE.version}, ${dylibBytes.length} bytes, target ${target})`,
);

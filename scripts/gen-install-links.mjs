#!/usr/bin/env node
// Generates the one-click install deep links (Cursor, VS Code, VS Code Insiders) from the server's
// launch config (scripts/lib/launch-config.mjs, itself derived from server.json) and keeps them in
// the two places that show them. Hand-encoded base64 and percent-encoded payloads rot; this is the
// only writer, and `--check` (CI) fails on any drift.
//
//   node scripts/gen-install-links.mjs          # rewrite the marked region in each target
//   node scripts/gen-install-links.mjs --check  # exit 1 if a target is out of date
//
// Formats, from the vendors' docs (fetched 2026-10-10):
//   VS Code  https://code.visualstudio.com/api/extension-guides/ai/mcp
//            vscode:mcp/install?{JSON.stringify -> encodeURIComponent}   (Insiders: vscode-insiders:)
//   Cursor   https://cursor.com/docs/context/mcp/install-links
//            cursor://anysphere.cursor-deeplink/mcp/install?name=<name>&config=<base64 of the
//            server object, WITHOUT a name key>
// The claude.ai custom-connector flow has no documented deep link (it is a settings dialog), so it
// is prose in docs/src/content/docs/getting-started/install.md, not generated here.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { launchConfig } from "./lib/launch-config.mjs";

export const BEGIN_MARKER =
  "<!-- BEGIN INSTALL-LINKS (generated by scripts/gen-install-links.mjs; do not hand-edit) -->";
export const END_MARKER = "<!-- END INSTALL-LINKS -->";
export const INSTALL_TARGETS = Object.freeze([
  "README.md",
  "docs/src/content/docs/getting-started/install.md",
]);

const ROOT = join(dirname(new URL(import.meta.url).pathname), "..");

/** @returns {{ cursor: string, vscode: string, vscodeInsiders: string }} */
export function installLinks(launch = launchConfig()) {
  const server = {
    command: launch.command,
    args: launch.args,
    env: { [launch.configEnv]: launch.configPlaceholder },
  };
  const vscodePayload = encodeURIComponent(
    JSON.stringify({ name: launch.name, type: "stdio", ...server }),
  );
  const cursorConfig = Buffer.from(JSON.stringify(server)).toString("base64");
  return {
    cursor: `cursor://anysphere.cursor-deeplink/mcp/install?name=${encodeURIComponent(launch.name)}&config=${encodeURIComponent(cursorConfig)}`,
    vscode: `vscode:mcp/install?${vscodePayload}`,
    vscodeInsiders: `vscode-insiders:mcp/install?${vscodePayload}`,
  };
}

/** The marker-bracketed block, no trailing newline. */
export function renderRegion(links) {
  return [
    BEGIN_MARKER,
    `[![Add to Cursor](https://cursor.com/deeplink/mcp-install-dark.svg)](${links.cursor})`,
    `[![Install in VS Code](https://img.shields.io/badge/VS_Code-Install_obsidian--tc-0098FF?logo=visualstudiocode&logoColor=white)](${links.vscode})`,
    `[Install in VS Code Insiders](${links.vscodeInsiders})`,
    END_MARKER,
  ].join("\n");
}

function regionBounds(doc) {
  const starts = [...doc.matchAll(new RegExp(escapeRe(BEGIN_MARKER), "g"))];
  const ends = [...doc.matchAll(new RegExp(escapeRe(END_MARKER), "g"))];
  if (starts.length !== 1 || ends.length !== 1 || ends[0].index < starts[0].index) {
    throw new Error(
      `expected exactly one install-links marker pair, found ${starts.length} begin / ${ends.length} end`,
    );
  }
  return { start: starts[0].index, end: ends[0].index + END_MARKER.length };
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Replace the marked region of `doc` with `region`. */
export function replaceRegion(doc, region) {
  const { start, end } = regionBounds(doc);
  // concatenation, not String.replace: a replacement string would expand `$&` sequences
  return `${doc.slice(0, start)}${region}${doc.slice(end)}`;
}

/** Problems (empty = in sync) for every target. `read` is injectable for tests. */
export function checkTargets(root = ROOT, read = (f) => readFileSync(join(root, f), "utf8")) {
  const region = renderRegion(installLinks());
  const problems = [];
  for (const f of INSTALL_TARGETS) {
    let doc;
    try {
      doc = read(f);
      const { start, end } = regionBounds(doc);
      if (doc.slice(start, end) !== region) {
        problems.push(
          `${f}: install-links region is out of date; run \`node scripts/gen-install-links.mjs\``,
        );
      }
    } catch (e) {
      problems.push(`${f}: ${e.message}`);
    }
  }
  return problems;
}

function main() {
  if (process.argv.includes("--check")) {
    const problems = checkTargets();
    if (problems.length) {
      console.error(`FAIL:\n  ${problems.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`install-links OK (${INSTALL_TARGETS.length} targets)`);
    return;
  }
  const region = renderRegion(installLinks());
  for (const f of INSTALL_TARGETS) {
    const path = join(ROOT, f);
    writeFileSync(path, replaceRegion(readFileSync(path, "utf8"), region));
    console.log(`  wrote ${f}`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();

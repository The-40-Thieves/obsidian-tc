// Rendering and parsing of packages/server/src/db/migrations-embedded.ts.
//
// Shared by the generator (scripts/gen-embedded-migrations.mjs) and the `regen` merge driver
// (scripts/merge-drivers/regen.mjs). The driver merges two branches' copies of the file as DATA —
// entry by entry — and re-renders through this same function, so a merged file is byte-identical to
// what `bun run migrations:embed` would write for the merged set of migrations, rather than a text
// splice that merely happens to parse.

/** The full module text for `entries`: an array of `[filename, sql]`, rendered in filename order. */
export function renderEmbedded(entries) {
  const sorted = [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  // JSON.stringify gives a correctly escaped TS string literal for any content — quotes,
  // backslashes, newlines and non-ASCII alike. Deliberately not a template literal: SQL can
  // contain a backtick or ${, both of which would break one.
  const body = sorted
    .map(([f, sql]) => `  ${JSON.stringify(f)}: ${JSON.stringify(sql)},`)
    .join("\n");
  return `// GENERATED by scripts/gen-embedded-migrations.mjs — DO NOT EDIT.
// Run \`bun run migrations:embed\` after adding, removing or editing a migration.
//
// THE-578: the migration SQL is inlined here rather than read from disk so that provisioning works
// in the standalone binaries. \`bun build --compile\` bakes import.meta.url to the build-time path
// and embeds no .sql files, which made every published binary fail at module load with an ENOENT
// against the CI runner's directory. Inlining removes the filesystem from this path entirely, and
// keeps one code path across vitest, \`bun run\`, the npm dist build and --compile.
//
// Regenerating is drift-gated: \`bun run migrations:embed:check\` fails CI if this file does not
// match packages/server/src/migrations/.

/** Migration filename -> its SQL, for every file under packages/server/src/migrations. */
export const EMBEDDED_MIGRATIONS: Readonly<Record<string, string>> = {
${body}
};

/** The SQL for \`file\`. Throws rather than returning undefined: a missing migration must fail loudly
 *  at startup, not provision a partial schema that breaks later as "no such table". */
export function embeddedSql(file: string): string {
  const sql = EMBEDDED_MIGRATIONS[file];
  if (sql === undefined) {
    throw new Error(
      \`migration "\${file}" is not embedded — run \\\`bun run migrations:embed\\\` after adding it\`,
    );
  }
  return sql;
}
`;
}

const ENTRY_LINE = /^ {2}("(?:[^"\\]|\\.)*"): ("(?:[^"\\]|\\.)*"),$/;

/**
 * `[filename, sql]` pairs read back from a rendered module. Strict: every line between the
 * `EMBEDDED_MIGRATIONS` opener and its `};` must be an entry, so a hand-edited or conflict-marked
 * file throws instead of being half-read.
 */
export function parseEmbedded(text) {
  const open = text.indexOf("export const EMBEDDED_MIGRATIONS");
  const start = open === -1 ? -1 : text.indexOf("= {\n", open);
  const end = start === -1 ? -1 : text.indexOf("\n};\n", start);
  if (start === -1 || end === -1)
    throw new Error("migrations-embedded.ts: EMBEDDED_MIGRATIONS block not found");
  const lines = text
    .slice(start + 4, end)
    .split("\n")
    .filter((l) => l !== "");
  return lines.map((line) => {
    const m = ENTRY_LINE.exec(line);
    if (!m) throw new Error(`migrations-embedded.ts: unparseable entry line: ${line.slice(0, 80)}`);
    return [JSON.parse(m[1]), JSON.parse(m[2])];
  });
}

/**
 * Three-way merge at entry granularity. Returns `{ entries }` or `{ conflicts: [filename...] }`.
 * A side that did not touch an entry defers to the other; two sides that changed the SAME entry
 * differently (or added the same name with different SQL) is a real conflict, never guessed.
 */
export function mergeEmbedded(ancestor, ours, theirs) {
  const o = new Map(ancestor);
  const a = new Map(ours);
  const b = new Map(theirs);
  const names = new Set([...o.keys(), ...a.keys(), ...b.keys()]);
  const entries = [];
  const conflicts = [];
  for (const name of names) {
    const ov = o.get(name);
    const av = a.get(name);
    const bv = b.get(name);
    let pick;
    if (av === bv) pick = av;
    else if (av === ov) pick = bv;
    else if (bv === ov) pick = av;
    else {
      conflicts.push(name);
      continue;
    }
    if (pick !== undefined) entries.push([name, pick]);
  }
  return conflicts.length > 0 ? { conflicts: conflicts.sort() } : { entries };
}
